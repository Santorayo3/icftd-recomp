# Generates src\assetExport\Recomp\CycleTable.cs from the interpreter's own 68000 cycle table.
#
#   powershell -ExecutionPolicy Bypass -File tools\gen-cycles.ps1 [-SkipBuild]
#
# Musashi builds `m68ki_cycles[0][opcode]` from the 68000 timing table at reset; the oracle dumps it
# with --cyclestable. The translated build bakes those numbers into the emitted code, so an
# instruction costs exactly what the interpreter charges for it and there is no runtime table (which
# the DOS build could not afford anyway). Rerun this only when the instruction model changes.
param([switch]$SkipBuild)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

if (-not $SkipBuild) {
    & powershell -NoProfile -ExecutionPolicy Bypass -File tools\build-oracle.ps1 | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'oracle build failed' }
}

$bin = Join-Path $root 'out\cycles.bin'
& (Join-Path $root 'bin\win32\icftd-oracle.exe') 'export\code\dshell4k\dshell.img' '0x4000' '0' '--cyclestable' $bin |
    ForEach-Object { "$_" }
if ($LASTEXITCODE -ne 0) { throw 'cycle table dump failed' }

$bytes = [System.IO.File]::ReadAllBytes($bin)
if ($bytes.Length -ne 65536) { throw "expected 65536 bytes, got $($bytes.Length)" }

# A histogram keeps the number plausible: the 68000 range is 4..~200 with a strong mode near 4-12.
$hist = @{}
foreach ($b in $bytes) { if ($hist.ContainsKey($b)) { $hist[$b]++ } else { $hist[$b] = 1 } }
$top = $hist.GetEnumerator() | Sort-Object -Property Value -Descending | Select-Object -First 6
Write-Output ('cycles: ' + (($top | ForEach-Object { "$($_.Key)=$($_.Value)" }) -join ' '))

$b64 = [Convert]::ToBase64String($bytes)
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// <auto-generated>')
[void]$sb.AppendLine('//   tools\gen-cycles.ps1 - do not edit by hand.')
[void]$sb.AppendLine('//')
[void]$sb.AppendLine('// The 68000 cycle cost of every opcode word, as the interpreter itself counts them: Musashi builds')
[void]$sb.AppendLine('// this table from the 68000 timing table at reset, the oracle dumps it (--cyclestable), and the')
[void]$sb.AppendLine('// emitter puts the number for each instruction into the generated C. That keeps the translated')
[void]$sb.AppendLine('// stream on the same clock as the interpreter without a runtime table (src\oracle\cpu.c,')
[void]$sb.AppendLine('// oracle_cycle_cost, reads the same numbers).')
[void]$sb.AppendLine('// </auto-generated>')
[void]$sb.AppendLine('using System;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace ICFTD.AmigaExport.Recomp;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('public static class CycleTable')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    const string B64 =')
for ($i = 0; $i -lt $b64.Length; $i += 100) {
    $len = [Math]::Min(100, $b64.Length - $i)
    [void]$sb.AppendLine(('        "' + $b64.Substring($i, $len) + '"' + $(if ($i + $len -lt $b64.Length) { ' +' } else { ';' })))
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    static readonly byte[] Cost = Convert.FromBase64String(B64);')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    /// <summary>Cycles the instruction with this opcode word takes.</summary>')
[void]$sb.AppendLine('    public static int Of(ushort op) => Cost[op];')
[void]$sb.AppendLine('}')
[void]$sb.AppendLine('')

$out = Join-Path $root 'src\assetExport\Recomp\CycleTable.cs'
[System.IO.File]::WriteAllText($out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Output "wrote $out"
