# Writes src\runtime\plat\win32\border_art.h: the art the Windows presenter paints behind the game
# view when fullscreen leaves bars either side of the 4:3 picture.
#
#   powershell -ExecutionPolicy Bypass -File tools\mkborder.ps1
#
# The port's own artwork (assets\border.png), not decoded from the game: a 16:9 backdrop - curtains
# left and right, black across the middle - authored with the 4:3 picture's own footprint at its
# centre. The platform layer stretches it over the whole window (point sampling, see border.c) and
# the picture covers the black centre, so a widescreen window shows curtain in the bars instead of
# black.
#
# The picture is a shaded curtain, not a flat cartoon: it has thousands of colours, so an 8-bit
# palette would quantise it (bands in the folds). It is stored run-length encoded instead - count,
# R, G, B per run, runs free to cross rows because the picture is one flat image - which is exact
# and about a third of the raw size.
param(
    [string]$Png = "assets\border.png",
    [string]$Out = "src\runtime\plat\win32\border_art.h",
    [int]$MaxRun = 255,              # the count is one byte
    [int]$RunsPerLine = 4
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

if (-not (Test-Path $Png)) { throw "no $Png - the border artwork lives in assets\" }
Add-Type -AssemblyName System.Drawing

$img = [System.Drawing.Bitmap]::FromFile((Resolve-Path $Png).Path)
$w = $img.Width
$h = $img.Height

# 32bpp, so the channels come out exactly as stored and the stride is a plain width*4 (a 24bpp
# LockBits row is padded, which is an easy way to read the picture one pixel out).
$rect = New-Object System.Drawing.Rectangle 0, 0, $w, $h
$data = $img.LockBits($rect, [System.Drawing.Imaging.ImageLockMode]::ReadOnly,
                      [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$raw = New-Object byte[] ($data.Stride * $h)
[System.Runtime.InteropServices.Marshal]::Copy($data.Scan0, $raw, 0, $raw.Length)
$stride = $data.Stride
$img.UnlockBits($data)
$img.Dispose()

# Runs of (count, r, g, b) in row-major order. A run is flushed before the colour changes or when it
# reaches MaxRun, so the decoder only has to fill.
$runs = New-Object System.Collections.Generic.List[byte]
$prevR = -1; $prevG = -1; $prevB = -1; $count = 0; $n = 0
for ($y = 0; $y -lt $h; $y++) {
    $o = $y * $stride
    for ($x = 0; $x -lt $w; $x++) {
        $b = [int]$raw[$o]; $g = [int]$raw[$o + 1]; $r = [int]$raw[$o + 2]
        $o += 4
        if ($r -ne $prevR -or $g -ne $prevG -or $b -ne $prevB -or $count -eq $MaxRun) {
            if ($count -gt 0) {
                $runs.Add([byte]$count); $runs.Add([byte]$prevR)
                $runs.Add([byte]$prevG); $runs.Add([byte]$prevB)
                $n++
            }
            $prevR = $r; $prevG = $g; $prevB = $b; $count = 0
        }
        $count++
    }
}
$runs.Add([byte]$count); $runs.Add([byte]$prevR); $runs.Add([byte]$prevG); $runs.Add([byte]$prevB)
$n++

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("/* Generated by tools\mkborder.ps1 from $Png - the port's border art. Do not edit. */")
[void]$sb.AppendLine("#define BORDER_W $w")
[void]$sb.AppendLine("#define BORDER_H $h")
[void]$sb.AppendLine("#define BORDER_RUNS $n")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("/* Run-length encoded, row-major, a run free to cross a row: count, R, G, B. */")
[void]$sb.AppendLine("static const u8 g_borderRuns[BORDER_RUNS * 4] =")
[void]$sb.AppendLine("{")
$line = "    "
for ($i = 0; $i -lt $runs.Count; $i += 4) {
    $line += ("{0},{1},{2},{3}," -f $runs[$i], $runs[$i + 1], $runs[$i + 2], $runs[$i + 3])
    if ((($i / 4) + 1) % $RunsPerLine -eq 0) { [void]$sb.AppendLine($line.TrimEnd()); $line = "    " }
}
if ($line.Trim().Length -gt 0) { [void]$sb.AppendLine($line.TrimEnd()) }
[void]$sb.AppendLine("};")

$text = $sb.ToString().Replace("`r`n", "`n")
[IO.File]::WriteAllText((Join-Path (Get-Location) $Out), $text, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "wrote $Out ($w x $h, $n run(s), $($runs.Count) bytes)"
