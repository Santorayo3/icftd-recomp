# Converts a PNG into the C table the runtime's OSD draws (src\runtime\amiga\osd_icon.h).
#
#   powershell -ExecutionPolicy Bypass -File tools\mkosdicon.ps1 assets\autosave.png
#
# Fully transparent pixels become 0; the remaining colours get 1..n in order of first appearance,
# and osd_icon.h ships their RGB triples next to the index grid.
param(
    [string]$Png = "assets\autosave.png",
    [string]$Out = "src\runtime\amiga\osd_icon.h"
)

Add-Type -AssemblyName System.Drawing

$im = [System.Drawing.Bitmap]::FromFile((Resolve-Path $Png))
$colours = New-Object System.Collections.Generic.List[string]
$rows = @()

for ($y = 0; $y -lt $im.Height; $y++) {
    $row = New-Object System.Collections.Generic.List[int]
    for ($x = 0; $x -lt $im.Width; $x++) {
        $c = $im.GetPixel($x, $y)
        if ($c.A -eq 0) { $row.Add(0); continue }
        $key = '{0},{1},{2}' -f $c.R, $c.G, $c.B
        if (-not $colours.Contains($key)) { $colours.Add($key) }
        $row.Add($colours.IndexOf($key) + 1)
    }
    $rows += ,$row
}
$w = $im.Width
$h = $im.Height
$im.Dispose()

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("/* Generated by tools\mkosdicon.ps1 from $Png - do not edit. */")
[void]$sb.AppendLine("#define OSD_ICON_W $w")
[void]$sb.AppendLine("#define OSD_ICON_H $h")
[void]$sb.AppendLine("#define OSD_ICON_COLOURS $($colours.Count)")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("/* RGB of the non-transparent colours, in index order. */")
[void]$sb.AppendLine("static const u8 g_osdIconPal[] =")
[void]$sb.AppendLine("{")
$line = "    "
for ($i = 0; $i -lt $colours.Count; $i++) {
    $line += "$($colours[$i]), "
}
[void]$sb.AppendLine($line.TrimEnd())
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("/* One byte per pixel, row by row: 0 = transparent, n = colour n-1. */")
[void]$sb.AppendLine("static const u8 g_osdIcon[OSD_ICON_H * OSD_ICON_W] =")
[void]$sb.AppendLine("{")
foreach ($row in $rows) {
    [void]$sb.AppendLine("    " + (($row | ForEach-Object { "$_" }) -join ",") + ",")
}
[void]$sb.AppendLine("};")

$text = $sb.ToString().Replace("`r`n", "`n")
[IO.File]::WriteAllText((Join-Path (Get-Location) $Out), $text, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "wrote $Out ($w x $h, $($colours.Count) colours)"
