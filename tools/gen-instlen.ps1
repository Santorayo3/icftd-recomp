# Turns the instruction-length table dumped by the oracle into a C file the runtime can use.
#
#   icftd-oracle.exe <image> --instlen out\instlen.bin
#   powershell -ExecutionPolicy Bypass -File tools\gen-instlen.ps1
#
# Why the table exists: the translated build never fetches its own instruction words - they are
# compiled - so charging the bus for them has to come from somewhere. Length is a function of the
# opcode word alone on a 68000 (an EA's extension words are fixed by its mode and register fields,
# MOVEM's mask is one word, an index word is one word), so one byte per opcode is exact.
param([string]$Bin = 'out\instlen.bin', [string]$Out = 'src\runtime\amiga\inst_len.c')
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Push-Location $root
if (-not (Test-Path $Bin)) { throw "$Bin missing - run: bin\win32\icftd-oracle.exe export\code\dshell4k\dshell.img --instlen $Bin" }
$b = [System.IO.File]::ReadAllBytes((Join-Path $root $Bin))
if ($b.Length -ne 65536) { throw "$Bin is $($b.Length) bytes, expected 65536" }

# Hand-checked cases: opcode -> words, from the 68000 programmer's reference (an instruction is its
# opcode word plus the extension words its addressing mode needs).
$cases = [ordered]@{
    '4E71' = 1; '4E75' = 1; '4E56' = 2; '4E90' = 1; '4EAC' = 2; '4EB9' = 3
    '203C' = 3; '11FC' = 3; '41F9' = 3; '3039' = 3; '48E7' = 2; '48C0' = 1
    '3140' = 2; '3030' = 2; '4EB0' = 2; '0668' = 3; '0C68' = 3; '6100' = 2
}
$bad = @()
foreach ($k in $cases.Keys) { $op = [Convert]::ToInt32($k, 16); if ($b[$op] -ne $cases[$k]) { $bad += ("{0}: table {1}, expected {2}" -f $k, $b[$op], $cases[$k]) } }
if ($bad.Count -gt 0) { throw ("instruction length table disagrees with the hand-checked cases:`n" + ($bad -join "`n")) }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/* Instruction lengths in 16-bit words, one byte per opcode word.')
[void]$sb.AppendLine(' *')
[void]$sb.AppendLine(' * GENERATED by tools\gen-instlen.ps1 from the oracle''s disassembler dump (--instlen); do not')
[void]$sb.AppendLine(' * edit. The translated build says its instruction words were fetched - they were compiled away -')
[void]$sb.AppendLine(' * and the bus charge for them is this many colour clocks, one per word.')
[void]$sb.AppendLine(' *')
[void]$sb.AppendLine(' * Hand-checked on 18 opcodes against the programmer''s reference; length depends on the opcode')
[void]$sb.AppendLine(' * word alone on a 68000. */')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('#include "types.h"')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('const u8 rt_inst_len[0x10000] = {')
for ($i = 0; $i -lt 65536; $i += 16) {
    $row = @()
    for ($j = 0; $j -lt 16; $j++) { $row += ('{0}' -f $b[$i + $j]) }
    [void]$sb.AppendLine(('    {0},' -f ($row -join ',')))
}
[void]$sb.AppendLine('};')
[System.IO.File]::WriteAllText((Join-Path $root $Out), $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "-> $Out (($cases.Count) cases checked)"
Pop-Location