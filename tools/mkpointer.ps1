# Writes src\runtime\amiga\pointer_art.h: the arrow the room screens show under the mouse.
#
#   powershell -ExecutionPolicy Bypass -File tools\mkpointer.ps1
#
# The port's own artwork, not decoded from the game: a 17x18 arrow with its tip at the top left,
# the same shape and size as the situation map's cursor (whose sprite sits 0x11/0x12 down-right of
# the point it is on - see src\host\main.c), so the pointer looks the same wherever it appears.
# `o` is the outline, `#` the fill, `.` transparent; the runtime draws them with the two pens the
# on-screen display reserves and sets (OSD_PEN_PTR, OSD_PEN_PTR+1).
param(
    [string]$Out = "src\runtime\amiga\pointer_art.h"
)

$art = @(
    '#................',
    'o##..............',
    '.####............',
    '.o#####..........',
    '..#######........',
    '..o#####o........',
    '...#####.........',
    '...o#####........',
    '....#oo###.......',
    '....o..o###......',
    '........o###.....',
    '.........o###....',
    '..........o###...',
    '...........o###..',
    '............o###.',
    '.............o###',
    '..............o#o',
    '...............o.'
)
$h = $art.Count
$w = $art[0].Length
for ($y = 0; $y -lt $h; $y++) {
    if ($art[$y].Length -ne $w) { throw "row $y is $($art[$y].Length) wide, expected $w" }
}

# 1 = outline (black), 2 = fill (white).
$pal = @(0, 0, 0, 255, 255, 255)

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("/* Generated by tools\mkpointer.ps1 - the port's pointer arrow. Do not edit. */")
[void]$sb.AppendLine("#define PTR_W $w")
[void]$sb.AppendLine("#define PTR_H $h")
[void]$sb.AppendLine("#define PTR_COLOURS 2")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("/* RGB of the non-transparent colours, in index order. */")
[void]$sb.AppendLine("static const u8 g_pointerPal[PTR_COLOURS * 3] =")
[void]$sb.AppendLine("{")
[void]$sb.AppendLine("    " + ($pal -join ', ') + ",")
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("/* One byte per pixel, row by row: 0 = transparent, n = colour n-1. */")
[void]$sb.AppendLine("static const u8 g_pointer[PTR_H * PTR_W] =")
[void]$sb.AppendLine("{")
foreach ($row in $art) {
    $vals = @()
    foreach ($ch in $row.ToCharArray()) {
        switch ($ch) {
            '.' { $vals += '0' }
            'o' { $vals += '1' }
            '#' { $vals += '2' }
            default { throw "unknown pixel '$ch'" }
        }
    }
    [void]$sb.AppendLine("    " + ($vals -join ',') + ",")
}
[void]$sb.AppendLine("};")

$text = $sb.ToString().Replace("`r`n", "`n")
[IO.File]::WriteAllText((Join-Path (Get-Location) $Out), $text, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "wrote $Out ($w x $h)"
