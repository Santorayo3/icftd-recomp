# Converts the title menu's button pictures into the C tables src\host\title_buttons.h.
#
#   powershell -ExecutionPolicy Bypass -File tools\mktitlebuttons.ps1
#
# A button is two pictures - normal and hover - and both are kept byte-exact: one byte per pixel,
# the PNG's own palette index (0 = the black outline, 1 = the fill), plus the two colours of the
# palette each was drawn with. There is no quantisation step, exactly like tools\mktitleart.ps1:
# the pictures are the shipped art.
param(
    [string]$Normal = "assets\btn_normal.png",
    [string]$Hover = "assets\btn_hover.png",
    [string]$Out = "src\host\title_buttons.h"
)

Add-Type -AssemblyName System.Drawing

function Read-Indexed([string]$path)
{
    $im = [System.Drawing.Bitmap]::FromFile((Resolve-Path $path))
    try {
        $w = $im.Width
        $h = $im.Height
        $fmt = $im.PixelFormat
        $rect = New-Object System.Drawing.Rectangle 0, 0, $w, $h
        if ($fmt -eq [System.Drawing.Imaging.PixelFormat]::Format8bppIndexed) {
            $lock = [System.Drawing.Imaging.PixelFormat]::Format8bppIndexed
        } elseif ($fmt -eq [System.Drawing.Imaging.PixelFormat]::Format4bppIndexed) {
            $lock = [System.Drawing.Imaging.PixelFormat]::Format4bppIndexed
        } else {
            throw "$path is $fmt; save it as an indexed PNG (4 or 8 bits per pixel)"
        }
        $data = $im.LockBits($rect, [System.Drawing.Imaging.ImageLockMode]::ReadOnly, $lock)
        try {
            $raw = New-Object byte[] ($data.Stride * $h)
            [System.Runtime.InteropServices.Marshal]::Copy($data.Scan0, $raw, 0, $raw.Length)
            $stride = $data.Stride
        } finally {
            $im.UnlockBits($data)
        }
        $idx = New-Object byte[] ($w * $h)
        for ($y = 0; $y -lt $h; $y++) {
            for ($x = 0; $x -lt $w; $x++) {
                if ($lock -eq [System.Drawing.Imaging.PixelFormat]::Format8bppIndexed) {
                    $v = $raw[$y * $stride + $x]
                } else {
                    $b = $raw[$y * $stride + [int][Math]::Floor($x / 2)]
                    $v = if (($x % 2) -eq 0) { ($b -shr 4) -band 0x0F } else { $b -band 0x0F }
                }
                $idx[$y * $w + $x] = [byte]$v
            }
        }
        $pal = @()
        for ($i = 0; $i -lt 2; $i++) {
            if ($i -ge $im.Palette.Entries.Count) { throw "$path has no palette entry $i" }
            $c = $im.Palette.Entries[$i]
            $pal += , @([int]$c.R, [int]$c.G, [int]$c.B)
        }
        return @{ w = $w; h = $h; idx = $idx; pal = $pal }
    } finally {
        $im.Dispose()
    }
}

$n = Read-Indexed $Normal
$v = Read-Indexed $Hover
if ($n.w -ne $v.w -or $n.h -ne $v.h) {
    throw "$Normal is $($n.w)x$($n.h), $Hover is $($v.w)x$($v.h); both states must be the same size"
}
foreach ($p in @(@{ name = $Normal; img = $n }, @{ name = $Hover; img = $v })) {
    foreach ($b in $p.img.idx) {
        if ($b -gt 1) { throw "$($p.name) uses palette index $b; a button is outline (0) and fill (1)" }
    }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("/* Generated by tools\mktitlebuttons.ps1 from $Normal and $Hover - do not edit. */")
[void]$sb.AppendLine("#define TITLE_BUTTON_W $($n.w)")
[void]$sb.AppendLine("#define TITLE_BUTTON_H $($n.h)")
[void]$sb.AppendLine("#define TITLE_BUTTON_COLOURS 2")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("/* One byte per pixel, the PNG's own palette index: 0 is the black outline, 1 the fill. */")
foreach ($p in @(@{ name = 'Normal'; img = $n }, @{ name = 'Hover'; img = $v })) {
    [void]$sb.AppendLine("static const u8 g_titleButton$($p.name)[TITLE_BUTTON_H * TITLE_BUTTON_W] =")
    [void]$sb.AppendLine("{")
    for ($y = 0; $y -lt $p.img.h; $y++) {
        $line = "    "
        for ($x = 0; $x -lt $p.img.w; $x++) {
            $line += ("{0}," -f $p.img.idx[$y * $p.img.w + $x])
        }
        [void]$sb.AppendLine($line.TrimEnd())
    }
    [void]$sb.AppendLine("};")
    [void]$sb.AppendLine("")
}
foreach ($p in @(@{ name = 'Normal'; img = $n }, @{ name = 'Hover'; img = $v })) {
    [void]$sb.AppendLine("/* $($p.name): the palette the picture was drawn with, RGB. */")
    [void]$sb.AppendLine("static const u8 g_titleButton$($p.name)Pal[TITLE_BUTTON_COLOURS * 3] =")
    [void]$sb.AppendLine("{")
    [void]$sb.AppendLine(("    {0},{1},{2}, {3},{4},{5}" -f $p.img.pal[0][0], $p.img.pal[0][1],
                         $p.img.pal[0][2], $p.img.pal[1][0], $p.img.pal[1][1], $p.img.pal[1][2]))
    [void]$sb.AppendLine("};")
    [void]$sb.AppendLine("")
}

$text = $sb.ToString().Replace("`r`n", "`n")
[IO.File]::WriteAllText((Join-Path (Get-Location) $Out), $text, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "wrote $Out ($($n.w) x $($n.h), 2 colours)"
