$liveMain = @'
/* Generated by tools\pad-check.ps1: builds the shipped Win32 platform layer, asks DirectInput
 * whether this machine has a game controller, and - when it has one - asserts that plat_pump
 * reports it and that the stick at rest is inside the deadzone (no direction). */
#include <windows.h>
#include <stdio.h>
#include <string.h>
#include <dinput.h>
#include "types.h"
#include "platform.h"
#include "pad.h"

typedef HRESULT (WINAPI *di8create_fn)(HINSTANCE, DWORD, REFIID, LPVOID *, LPUNKNOWN);

static const GUID g_iid =
    { 0xBF798030, 0x483A, 0x4DA2, { 0xAA, 0x99, 0x5D, 0x64, 0xED, 0x36, 0x97, 0x00 } };

static int g_count;
static char g_name[256];

static BOOL CALLBACK count_cb(LPCDIDEVICEINSTANCEA inst, LPVOID ctx)
{
    if (g_count == 0) strncpy(g_name, inst->tszProductName, sizeof g_name - 1);
    g_count++;
    return DIENUM_CONTINUE;
}

static int pads_attached(void)
{
    HMODULE dll;
    di8create_fn create;
    LPDIRECTINPUT8A di = 0;

    CoInitialize(0);
    dll = LoadLibraryA("dinput8.dll");
    if (dll == 0) return 0;
    create = (di8create_fn)GetProcAddress(dll, "DirectInput8Create");
    if (create == 0) return 0;
    if (FAILED(create(GetModuleHandle(0), 0x0800, &g_iid, (LPVOID *)&di, 0)) || di == 0) return 0;
    IDirectInput8_EnumDevices(di, DI8DEVCLASS_GAMECTRL, count_cb, 0, DIEDFL_ATTACHEDONLY);
    IDirectInput8_Release(di);
    return g_count;
}

int main(void)
{
    static input_state in;
    HWND h;
    int i, seen = 0;

    if (pads_attached() == 0) { printf("pad: SKIP (no game controller attached)\n"); return 2; }
    printf("pad: this machine has %d game controller(s), first '%s'\n", g_count, g_name);

    if (!plat_init("ICFTD pad-check")) { printf("pad: SKIP (no window)\n"); return 2; }
    h = FindWindow("ICFTD", "ICFTD pad-check");
    if (h != 0) SetForegroundWindow(h);
    for (i = 0; i < 300 && !seen; i++)
    {
        memset(&in, 0, sizeof in);
        if (!plat_pump(&in)) break;
        if (in.pad_present) { seen = 1; break; }
        Sleep(10);
    }
    if (!seen)
    {
        printf("FAIL pad: a game controller is attached, but plat_pump reports no pad\n");
        plat_shutdown();
        return 1;
    }
    printf("pad: the platform reports the pad: stick %d,%d, d-pad %d%d%d%d, fire %d, start %d\n",
           (int)in.pad_x, (int)in.pad_y, in.pad_up, in.pad_down, in.pad_left, in.pad_right,
           in.pad_fire, in.pad_start);
    if (host_pad_dirs(&in) != 0)
    {
        printf("FAIL pad: the stick at rest reports a direction (%d,%d)\n", (int)in.pad_x,
               (int)in.pad_y);
        plat_shutdown();
        return 1;
    }
    printf("pad: the stick at rest is inside the deadzone - no direction, no drift\n");
    plat_shutdown();
    return 0;
}
