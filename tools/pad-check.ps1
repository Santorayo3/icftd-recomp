# The gamepad (a port feature: host input plumbing).
#
#   powershell -ExecutionPolicy Bypass -File tools\pad-check.ps1
#
# The pad itself cannot be scripted - no API lets a program press a button - so the check measures
# the two halves separately:
#
#   1. The mapping (src\host\pad.c, the shipped file): synthetic `input_state`s are fed through it
#      and the keys, the click and the pointer it produces are asserted - the d-pad is the four
#      directions with one press edge per press, any face button is /FIRE and a click, Start is
#      Escape, and the stick's deflection is the pointer's speed (a small push moves it less than a
#      full one, and it stops at the picture's edges). This is the part a player feels, and it runs
#      everywhere.
#
#   2. The read (src\runtime\plat\win32\plat_win32.c): when this machine has a game controller, the
#      shipped platform layer is built and pumped and has to report it - DirectInput8 is what sees a
#      PlayStation pad here (measured; XInput does not report one), so this is what catches a broken
#      enumeration, data format or acquisition. The pad at rest must sit inside the deadzone, i.e.
#      report no direction. With no pad attached (or no window) the step is a SKIP (exit 0).
param(
    [string]$Work = 'out\pad-check',
    [string]$WatcomHome = $(if ($env:WATCOM) { $env:WATCOM } else { 'H:\Meine Programme\Open Watcom' })
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$wcl = Join-Path $WatcomHome 'binnt64\wcl386.exe'
if (-not (Test-Path $wcl)) { Write-Output "pad: SKIP (no $wcl)"; exit 0 }

$env:WATCOM = $WatcomHome
# The DirectX headers ship inside Open Watcom (h\nt\directx): plat_win32.c's true-colour
# presenter is built from them (docs\display-rate.md, phase 3).
$env:INCLUDE = @((Join-Path $WatcomHome 'h'), (Join-Path $WatcomHome 'h\nt'),
                 (Join-Path $WatcomHome 'h\nt\directx')) -join ';'
$env:LIB = @((Join-Path $WatcomHome 'lib386'), (Join-Path $WatcomHome 'lib386\nt')) -join ';'
$env:PATH = @((Join-Path $WatcomHome 'binnt64'), (Join-Path $WatcomHome 'binnt')) -join ';'

New-Item -ItemType Directory -Force -Path $Work | Out-Null

# --- 1. the mapping ------------------------------------------------------------------------------
$main = @'
/* Generated by tools\pad-check.ps1: feeds synthetic pad states through the shipped
 * src\host\pad.c and prints what the front end's input_state gets, so the mapping is asserted on
 * the state the game reads rather than on a picture. */
#include <stdio.h>
#include <string.h>
#include "types.h"
#include "platform.h"
#include "pad.h"

static int      g_fail;
static host_pad g_pad;
static input_state g_in;

static void want(const char *what, int ok, const char *detail)
{
    if (!ok) { printf("FAIL pad: %s (%s)\n", what, detail); g_fail++; }
    else      printf("pad: %-52s %s\n", what, detail);
}

/* A fresh frame, as plat_pump hands one over: the platform clears the level state each time, so
 * only what the pad puts in it survives. */
static void fresh(void)
{
    memset(&g_in, 0, sizeof g_in);
    g_in.pad_present = 1;
}

static void reset_pad(void)
{
    memset(&g_pad, 0, sizeof g_pad);
}

/* What the mouse reports while the stick is used: plat_pump fills the position from the mouse
 * every frame, and the host hands the same buffer on, so a frame starts from here. */
static s16 g_platX, g_platY;

/* One frame, the way plat_pump and the frame hook do it: the platform's pointer fields, then the
 * stick. The result is read out of g_in.mouse_x/mouse_y. */
static int frame_cursor(void)
{
    g_in.mouse_x = g_platX;
    g_in.mouse_y = g_platY;
    return host_pad_cursor(&g_pad, &g_in);
}

static int run_cursor(int frames)
{
    int i;
    for (i = 0; i < frames; i++) frame_cursor();
    return g_in.mouse_x;
}

int main(void)
{
    int full, small, tiny;

    /* 0. No pad: nothing changes. */
    memset(&g_in, 0, sizeof g_in);
    g_in.mouse_x = 40;
    g_in.mouse_y = 30;
    reset_pad();
    host_pad_buttons(&g_pad, &g_in);
    want("no pad leaves the keys alone",
         !g_in.down[KEY_FIRE] && !g_in.pressed[KEY_ESCAPE] && !g_in.mouse_left &&
         !g_in.mouse_left_pressed, "no key, no click");
    want("no pad leaves the pointer alone",
         !host_pad_cursor(&g_pad, &g_in) && g_in.mouse_x == 40 && !g_in.mouse_moved,
         "no move");
    want("no pad reports no direction", host_pad_dirs(&g_in) == 0, "0");

    /* 1. The d-pad is the four directions, one press edge per press. */
    reset_pad();
    fresh(); g_in.pad_up = 1;
    host_pad_buttons(&g_pad, &g_in);
    want("d-pad up is the Up key", g_in.down[KEY_UP] && g_in.pressed[KEY_UP], "down and pressed");
    fresh(); g_in.pad_up = 1;
    host_pad_buttons(&g_pad, &g_in);
    want("a held d-pad is one press", g_in.down[KEY_UP] && !g_in.pressed[KEY_UP],
         "still down, no second edge");
    fresh();
    host_pad_buttons(&g_pad, &g_in);
    want("a released d-pad is no direction", !g_in.down[KEY_UP], "up is clear");
    fresh(); g_in.pad_up = 1;
    host_pad_buttons(&g_pad, &g_in);
    want("a re-press is a new press", g_in.pressed[KEY_UP], "the edge is back");
    reset_pad();

    {
        fresh(); g_in.pad_down = 1;
        host_pad_buttons(&g_pad, &g_in);
        want("d-pad down is the Down key", g_in.down[KEY_DOWN] && g_in.pressed[KEY_DOWN], "down");
        reset_pad();
        fresh(); g_in.pad_left = 1;
        host_pad_buttons(&g_pad, &g_in);
        want("d-pad left is the Left key", g_in.down[KEY_LEFT] && g_in.pressed[KEY_LEFT], "left");
        reset_pad();
        fresh(); g_in.pad_right = 1;
        host_pad_buttons(&g_pad, &g_in);
        want("d-pad right is the Right key", g_in.down[KEY_RIGHT] && g_in.pressed[KEY_RIGHT], "right");
        reset_pad();
    }

    /* 2. Any face button is /FIRE, and the port's click. A pad has one button; all four are it
     *    (the platform reports a single level, src\runtime\plat\win32\plat_win32.c). */
    reset_pad();
    fresh(); g_in.pad_fire = 1;
    host_pad_buttons(&g_pad, &g_in);
    want("a face button is /FIRE", g_in.down[KEY_FIRE] && g_in.pressed[KEY_FIRE] && g_in.mouse_left,
         "down, pressed, and the mouse's left button");
    want("a face button is one click", g_in.mouse_left_pressed, "the click edge is reported");
    fresh(); g_in.pad_fire = 1;
    host_pad_buttons(&g_pad, &g_in);
    want("a held button is one press", g_in.down[KEY_FIRE] && g_in.mouse_left &&
         !g_in.pressed[KEY_FIRE] && !g_in.mouse_left_pressed, "still down, no second edge");
    fresh();
    host_pad_buttons(&g_pad, &g_in);
    want("a released button releases /FIRE", !g_in.down[KEY_FIRE] && !g_in.mouse_left, "released");
    reset_pad();

    /* 3. Start is Escape. */
    fresh(); g_in.pad_start = 1;
    host_pad_buttons(&g_pad, &g_in);
    want("Start is Escape", g_in.down[KEY_ESCAPE] && g_in.pressed[KEY_ESCAPE], "down and pressed");
    fresh(); g_in.pad_start = 1;
    host_pad_buttons(&g_pad, &g_in);
    want("a held Start is one press", g_in.down[KEY_ESCAPE] && !g_in.pressed[KEY_ESCAPE],
         "no second edge");
    reset_pad();

    /* 4. The stick's deflection is the pointer's speed: a small push moves it less than a full
     *    one, and the deadzone moves nothing at all. */
    fresh(); g_in.pad_x = 6000;
    want("the stick inside its deadzone is no pointer", !host_pad_cursor(&g_pad, &g_in),
         "no move");
    want("the stick inside its deadzone is no direction", host_pad_dirs(&g_in) == 0, "0");

    reset_pad();
    fresh(); g_in.pad_x = 8100;
    tiny = run_cursor(20);
    reset_pad();
    fresh(); g_in.pad_x = 16000;
    small = run_cursor(20);
    reset_pad();
    fresh(); g_in.pad_x = 32767;
    full = run_cursor(20);
    printf("pad: 20 frames of a full push move the pointer %d px, a half push %d px, a nudge %d px\n",
           full, small, tiny);
    want("a full push crosses the screen", full == 120, "20 frames x 6 px (the default sensitivity)");
    want("a half push is slower than a full one", small > 0 && small < full, "fewer pixels");
    want("a nudge is slower than a half push", tiny > 0 && tiny < small, "fewer still");

    /* 4b. The speed is icftd.ini's [INPUT] pad_sensitivity: per cent of the pad's full speed,
     *     clamped to its range, defaulting to half. */
    host_pad_sensitivity(100);
    g_platX = 0; g_platY = 0;
    reset_pad(); fresh(); g_in.pad_x = 32767;
    small = run_cursor(20);
    want("sensitivity 100 is twice the default", small == 240, "20 frames x 12 px");
    host_pad_sensitivity(200);
    reset_pad(); fresh(); g_in.pad_x = 32767;
    tiny = run_cursor(5);
    want("sensitivity 200 is four times the default", tiny == 120, "5 frames x 24 px");
    host_pad_sensitivity(0);                    /* below the range: clamped to 10 */
    reset_pad(); fresh(); g_in.pad_x = 32767;
    small = run_cursor(20);
    want("a value outside the range is clamped", small > 10 && small < 40, "the 10% crawl");
    host_pad_sensitivity(PAD_SENSITIVITY_DEFAULT);

    /* 5. The stick's axes are the screen's: x right, y down. */
    reset_pad();
    g_platX = 100; g_platY = 50;
    fresh(); g_in.pad_x = 32767;
    frame_cursor();
    want("the stick starts where the pointer is",
         g_in.mouse_x == 106 && g_in.mouse_y == 50, "6 px right of the mouse, same row");
    reset_pad();
    fresh(); g_in.pad_y = 32767;
    frame_cursor();
    want("a push down moves the pointer down", g_in.mouse_x == 100 && g_in.mouse_y == 56,
         "6 px down, same column");
    reset_pad();
    fresh(); g_in.pad_x = -32767; g_in.pad_y = -32767;
    frame_cursor();
    want("a push up-left moves the pointer up-left",
         g_in.mouse_x == 94 && g_in.mouse_y == 44, "6 px each way");

    /* The pointer stays where the stick put it when the stick is let go: a centred stick is not a
     * release (the mouse takes the pointer back by moving, not by being idle). A pointer that
     * snapped back to the mouse's corner between two pushes is what the first play test found. */
    fresh();
    frame_cursor();
    want("a released stick leaves the pointer where it is",
         g_in.mouse_x == 94 && g_in.mouse_y == 44 && !g_in.mouse_moved,
         "the stick's 94,44, not the mouse's 100,50");
    g_platX = 200; g_platY = 20;                    /* the mouse moved: it has the pointer */
    fresh();
    frame_cursor();
    want("a moved mouse takes the pointer back", g_in.mouse_x == 200 && g_in.mouse_y == 20,
         "the mouse's 200,20");

    /* 6. The pointer stays on the picture. */
    g_platX = 0; g_platY = 0;
    reset_pad();
    fresh(); g_in.pad_x = 32767; g_in.pad_y = 32767;
    run_cursor(200);
    want("the pointer stops at the picture's far edge",
         g_in.mouse_x == SCREEN_W - 1 && g_in.mouse_y == SCREEN_H - 1, "319,199");
    g_platX = 5; g_platY = 5;
    reset_pad();
    fresh(); g_in.pad_x = -32767; g_in.pad_y = -32767;
    run_cursor(200);
    want("the pointer stops at the picture's near edge",
         g_in.mouse_x == 0 && g_in.mouse_y == 0, "0,0");

    /* 7. The stick as the four directions, in the joy word's own bit layout. */
    fresh(); g_in.pad_x = -32767;
    want("the stick left is the joy's left", host_pad_dirs(&g_in) == 4, "4");
    fresh(); g_in.pad_x = 32767;
    want("the stick right is the joy's right", host_pad_dirs(&g_in) == 8, "8");
    fresh(); g_in.pad_y = -32767;
    want("the stick up is the joy's up", host_pad_dirs(&g_in) == 1, "1");
    fresh(); g_in.pad_y = 32767;
    want("the stick down is the joy's down", host_pad_dirs(&g_in) == 2, "2");
    fresh(); g_in.pad_x = 32000; g_in.pad_y = -32000;
    want("a diagonal is both directions", host_pad_dirs(&g_in) == 9, "right and up");
    fresh(); g_in.pad_x = 7000; g_in.pad_y = -7000;
    want("a stick inside the deadzone is no direction", host_pad_dirs(&g_in) == 0, "0");

    if (g_fail != 0) { printf("FAIL pad: %d case(s) failed\n", g_fail); return 1; }
    printf("pad: the pad is the stick, the fire button and Escape, and its stick is the pointer\n");
    return 0;
}
