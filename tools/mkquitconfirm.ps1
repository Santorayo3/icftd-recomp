# Converts assets\quit_confirm.png into the C table the Escape confirmation draws
# (src\host\quit_confirm_art.h).
#
#   powershell -ExecutionPolicy Bypass -File tools\mkquitconfirm.ps1
#
# The picture is kept byte-exact: one byte per pixel, the PNG's own palette index, plus the colours
# of the palette it was drawn with. That is the same rule as the other port pictures, so a build
# never needs the PNG and tools\art-check.ps1 can prove the table is what the tracked picture is.
#
# The top-left pixel is the key colour: the cyan around the plaque is the picture's background, not
# part of the popup, so the drawing code leaves those pixels untouched.
param(
    [string]$Png = "assets\quit_confirm.png",
    [string]$Out = "src\host\quit_confirm_art.h"
)

Add-Type -AssemblyName System.Drawing

$im = [System.Drawing.Bitmap]::FromFile((Resolve-Path $Png))
try {
    $w = $im.Width
    $h = $im.Height
    $fmt = $im.PixelFormat
    $rect = New-Object System.Drawing.Rectangle 0, 0, $w, $h
    if ($fmt -eq [System.Drawing.Imaging.PixelFormat]::Format8bppIndexed) {
        $lock = [System.Drawing.Imaging.PixelFormat]::Format8bppIndexed
    } elseif ($fmt -eq [System.Drawing.Imaging.PixelFormat]::Format4bppIndexed) {
        $lock = [System.Drawing.Imaging.PixelFormat]::Format4bppIndexed
    } else {
        throw "$Png is $fmt; save it as an indexed PNG (4 or 8 bits per pixel)"
    }

    $data = $im.LockBits($rect, [System.Drawing.Imaging.ImageLockMode]::ReadOnly, $lock)
    try {
        $raw = New-Object byte[] ($data.Stride * $h)
        [System.Runtime.InteropServices.Marshal]::Copy($data.Scan0, $raw, 0, $raw.Length)
        $stride = $data.Stride
    } finally {
        $im.UnlockBits($data)
    }

    $idx = New-Object byte[] ($w * $h)
    $max = 0
    for ($y = 0; $y -lt $h; $y++) {
        for ($x = 0; $x -lt $w; $x++) {
            if ($lock -eq [System.Drawing.Imaging.PixelFormat]::Format8bppIndexed) {
                $v = $raw[$y * $stride + $x]
            } else {
                $b = $raw[$y * $stride + [int][Math]::Floor($x / 2)]
                $v = if (($x % 2) -eq 0) { ($b -shr 4) -band 0x0F } else { $b -band 0x0F }
            }
            $idx[$y * $w + $x] = [byte]$v
            if ($v -gt $max) { $max = $v }
        }
    }

    $palette = $im.Palette.Entries
    $count = $max + 1
    if ($count -gt $palette.Count) { throw "$Png uses palette index $max but has only $($palette.Count) entries" }
    $pal = @()
    for ($i = 0; $i -lt $count; $i++) {
        $c = $palette[$i]
        $pal += , @([int]$c.R, [int]$c.G, [int]$c.B)
    }
} finally {
    $im.Dispose()
}

$transparent = $idx[0]
if ($transparent -ge $count) { throw "$Png's top-left palette index $transparent has no colour" }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("/* Generated by tools\mkquitconfirm.ps1 from $Png - do not edit. */")
[void]$sb.AppendLine("#define QUIT_CONFIRM_W $w")
[void]$sb.AppendLine("#define QUIT_CONFIRM_H $h")
[void]$sb.AppendLine("#define QUIT_CONFIRM_COLOURS $count")
[void]$sb.AppendLine("#define QUIT_CONFIRM_TRANSPARENT $transparent   /* the top-left pixel's colour */")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("/* The palette the picture was drawn with, RGB. */")
[void]$sb.AppendLine("static const u8 g_quitConfirmPal[QUIT_CONFIRM_COLOURS * 3] =")
[void]$sb.AppendLine("{")
$line = "    "
for ($i = 0; $i -lt $count; $i++) {
    $line += ("{0},{1},{2}," -f $pal[$i][0], $pal[$i][1], $pal[$i][2])
    if ((($i + 1) % 4) -eq 0) { [void]$sb.AppendLine($line.TrimEnd()); $line = "    " }
}
if ($line.Trim().Length -gt 0) { [void]$sb.AppendLine($line.TrimEnd()) }
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("/* One byte per pixel, the PNG's own palette index. */")
[void]$sb.AppendLine("static const u8 g_quitConfirm[QUIT_CONFIRM_H * QUIT_CONFIRM_W] =")
[void]$sb.AppendLine("{")
for ($y = 0; $y -lt $h; $y++) {
    $line = "    "
    for ($x = 0; $x -lt $w; $x++) {
        $line += ("{0}," -f $idx[$y * $w + $x])
        if ((($x + 1) % 32) -eq 0) { [void]$sb.AppendLine($line.TrimEnd()); $line = "    " }
    }
    if ($line.Trim().Length -gt 0) { [void]$sb.AppendLine($line.TrimEnd()) }
}
[void]$sb.AppendLine("};")

$text = $sb.ToString().Replace("`r`n", "`n")
[IO.File]::WriteAllText((Join-Path (Get-Location) $Out), $text, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "wrote $Out ($w x $h, $count colours)"
