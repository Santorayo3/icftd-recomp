# The four directions, each on two keys (a port feature: host input plumbing).
#
#   powershell -ExecutionPolicy Bypass -File tools\keys-check.ps1
#
# The game moves with the arrow cluster; the port also answers W/A/S/D for the same four
# directions. There is nothing in the original to diff this against, so the claim is that a
# direction key and its letter are the *same input*: the check compiles the shipped
# src\runtime\plat\win32\plat_win32.c, posts the key messages a player would produce
# (WM_KEYDOWN / WM_KEYUP) at the window, and compares the input_state (src\runtime\platform.h) the
# platform hands the front end.
#
#   1. A press of A, S, D or W produces the input_state its arrow produces, down and pressed
#      alike. W is also the title's and the Ctrl+W cheat's own key, so for W the direction is
#      compared and KEY_W is asserted separately: it is the one word that may differ by design.
#   2. Two keys, one direction: holding both and releasing either keeps the direction down.
#      Releasing the last one releases it. (A plain level write would report a release while a
#      key is still held, and the player would stutter every time he switched keys.)
#   3. Nothing else moves: opposing keys still report both directions (the host's own joystick
#      word handles that case), and an arrow press does not set KEY_W.
#   4. A tap inside one frame: a key that goes down and up again before the next boundary is one
#      press, on every key the port maps (Escape, Enter, Space, F1..F5, the digit row, the
#      directions, W/C/T and left Ctrl). The window procedure latches the edge where the message
#      arrives - at display rate - and plat_pump reports it once and clears it, so a fast tap is
#      neither lost nor reported twice (docs\display-rate.md, phase 4).
#
# The driver needs a window, so with no desktop the step is a SKIP (exit 0) rather than a failure.
param(
    [string]$Work = 'out\keys-check',
    [string]$WatcomHome = $(if ($env:WATCOM) { $env:WATCOM } else { 'H:\Meine Programme\Open Watcom' })
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$wcl = Join-Path $WatcomHome 'binnt64\wcl386.exe'
if (-not (Test-Path $wcl)) { Write-Output "keys: SKIP (no $wcl)"; exit 0 }

$env:WATCOM = $WatcomHome
# The DirectX headers ship inside Open Watcom (h\nt\directx): plat_win32.c's true-colour
# presenter is built from them (docs\display-rate.md, phase 3).
$env:INCLUDE = @((Join-Path $WatcomHome 'h'), (Join-Path $WatcomHome 'h\nt'),
                 (Join-Path $WatcomHome 'h\nt\directx')) -join ';'
$env:LIB = @((Join-Path $WatcomHome 'lib386'), (Join-Path $WatcomHome 'lib386\nt')) -join ';'
$env:PATH = @((Join-Path $WatcomHome 'binnt64'), (Join-Path $WatcomHome 'binnt')) -join ';'

New-Item -ItemType Directory -Force -Path $Work | Out-Null
$main = @'
/* Generated by tools\keys-check.ps1: posts the key messages a player produces to the shipped Win32
 * platform layer and prints what input_state reports, so the arrow cluster and W/A/S/D can be
 * compared as the same input. */
#include <windows.h>
#include <stdio.h>
#include <string.h>
#include "types.h"
#include "platform.h"

static HWND        g_hwnd;
static input_state g_in;
static int         g_fail;

static void pump(void)
{
    plat_pump(&g_in);
}

static void keysend(UINT msg, UINT vk)
{
    PostMessage(g_hwnd, msg, (WPARAM)vk, 0);
    pump();
}

static int same_state(const input_state *a, const input_state *b)
{
    int i;

    for (i = 0; i < KEY_COUNT; i++)
        if (a->down[i] != b->down[i] || a->pressed[i] != b->pressed[i]) return 0;
    return 1;
}

static const char *dirs(void)
{
    static char text[8];

    sprintf(text, "%d%d%d%d", g_in.down[KEY_UP] ? 1 : 0, g_in.down[KEY_DOWN] ? 1 : 0,
            g_in.down[KEY_LEFT] ? 1 : 0, g_in.down[KEY_RIGHT] ? 1 : 0);
    return text;
}

/* want is the four direction bits as text, most significant being Up. */
static void want_dirs(const char *what, const char *want)
{
    if (strcmp(dirs(), want) != 0) {
        printf("FAIL keys: %s reports the directions %s, wanted %s\n", what, dirs(), want);
        g_fail++;
    } else
        printf("keys: %-34s directions %s\n", what, dirs());
}

static void want(const char *what, int ok, const char *detail)
{
    if (!ok) {
        printf("FAIL keys: %s (%s)\n", what, detail);
        g_fail++;
    } else
        printf("keys: %-34s %s\n", what, detail);
}

int main(void)
{
    static const struct { UINT vk; UINT wasd; const char *arrow; const char *letter; const char *bits; }
    pairs[4] = {
        { VK_UP,    'W', "Up",    "W", "1000" },
        { VK_DOWN,  'S', "Down",  "S", "0100" },
        { VK_LEFT,  'A', "Left",  "A", "0010" },
        { VK_RIGHT, 'D', "Right", "D", "0001" }
    };
    input_state arrow[4];
    int i;

    if (!plat_init("ICFTD keys-check")) { printf("keys: SKIP (no window)\n"); return 2; }
    g_hwnd = FindWindow("ICFTD", "ICFTD keys-check");
    if (!g_hwnd) { plat_shutdown(); printf("keys: SKIP (no window)\n"); return 2; }
    pump();
    want_dirs("no key", "0000");

    /* 1. What each arrow produces, kept for the comparison below. */
    for (i = 0; i < 4; i++) {
        keysend(WM_KEYDOWN, pairs[i].vk);
        want_dirs(pairs[i].arrow, pairs[i].bits);
        arrow[i] = g_in;
        keysend(WM_KEYUP, pairs[i].vk);
        want_dirs("released", "0000");
    }
    for (i = 0; i < 4; i++) {
        char what[64];

        keysend(WM_KEYDOWN, pairs[i].wasd);
        sprintf(what, "%s is %s", pairs[i].letter, pairs[i].arrow);
        if (pairs[i].wasd == 'W') {
            /* W is also the title's third ending and the cheat's letter, so KEY_W is the one word
             * that may differ: take it out and the rest must be the arrow's state. */
            input_state got = g_in;

            got.down[KEY_W] = 0;
            got.pressed[KEY_W] = 0;
            want(what, same_state(&got, &arrow[i]) != 0 && g_in.down[KEY_W] != 0,
                 "Up down, and KEY_W down (W is the title's own key too)");
        } else
            want(what, same_state(&g_in, &arrow[i]) != 0,
                 "the same input_state the arrow produces, down and pressed");
        keysend(WM_KEYUP, pairs[i].wasd);
        want_dirs("released", "0000");
    }

    /* 2. Two keys, one direction: the direction outlives the first release. */
    keysend(WM_KEYDOWN, 'A');
    keysend(WM_KEYDOWN, VK_LEFT);
    keysend(WM_KEYUP, VK_LEFT);
    want_dirs("A held, Left released", "0010");
    keysend(WM_KEYUP, 'A');
    want_dirs("both released", "0000");
    keysend(WM_KEYDOWN, VK_LEFT);
    keysend(WM_KEYDOWN, 'A');
    keysend(WM_KEYUP, 'A');
    want_dirs("Left held, A released", "0010");
    keysend(WM_KEYUP, VK_LEFT);
    want_dirs("both released", "0000");

    /* 3. Nothing else moved: opposing keys still report both, and an arrow is not W. */
    keysend(WM_KEYDOWN, 'A');
    keysend(WM_KEYDOWN, 'D');
    want_dirs("A and D held", "0011");
    keysend(WM_KEYUP, 'A');
    keysend(WM_KEYUP, 'D');
    keysend(WM_KEYDOWN, VK_UP);
    want("an arrow does not press W", g_in.down[KEY_UP] && !g_in.down[KEY_W],
         "KEY_W stays clear");
    keysend(WM_KEYUP, VK_UP);

    /* 4. A tap inside one frame: down and up before the next boundary is still one press. Both
     * messages are posted and only then pumped, which is exactly the state a key held for a few
     * milliseconds leaves when the boundary reads it. */
    {
        static const struct { UINT vk; int key; const char *name; } taps[] = {
            { VK_ESCAPE,  KEY_ESCAPE,  "Escape" },
            { VK_RETURN,  KEY_ENTER,   "Enter" },
            { VK_SPACE,   KEY_FIRE,    "Space" },
            { VK_F1,      KEY_F1,      "F1" },
            { VK_F2,      KEY_F2,      "F2" },
            { VK_F3,      KEY_F3,      "F3" },
            { VK_F4,      KEY_F4,      "F4" },
            { VK_F5,      KEY_F5,      "F5" },
            { '0',        KEY_0,       "0" },
            { '3',        KEY_3,       "3" },
            { '9',        KEY_9,       "9" },
            { VK_UP,      KEY_UP,      "Up" },
            { VK_LEFT,    KEY_LEFT,    "Left" },
            { 'W',        KEY_W,       "W" },
            { 'C',        KEY_C,       "C" },
            { 'T',        KEY_T,       "T" },
            { VK_CONTROL, KEY_CTRL,    "Left Ctrl" }
        };
        unsigned t;

        for (t = 0; t < sizeof taps / sizeof taps[0]; t++) {
            char what[96];

            pump();                                  /* a clean boundary first */
            PostMessage(g_hwnd, WM_KEYDOWN, (WPARAM)taps[t].vk, 0);
            PostMessage(g_hwnd, WM_KEYUP, (WPARAM)taps[t].vk, 0);
            pump();
            sprintf(what, "%s tapped inside one frame", taps[t].name);
            want(what, g_in.pressed[taps[t].key] && !g_in.down[taps[t].key],
                 "one pressed edge, and not held");
            pump();
            sprintf(what, "%s tap reported once", taps[t].name);
            want(what, !g_in.pressed[taps[t].key], "the next boundary has no edge");
        }
    }

    plat_shutdown();
    if (g_fail != 0) {
        printf("FAIL keys: %d case(s) failed\n", g_fail);
        return 1;
    }
    printf("keys: every direction is the same input from the arrow cluster and from W/A/S/D\n");
    return 0;
}
'@
Set-Content -Path (Join-Path $Work 'main.c') -Value $main -Encoding Ascii

Push-Location $Work
$built = $false
$prevEap = $ErrorActionPreference
# Native tools write warnings to stderr; with 'Stop' PowerShell would turn those into exceptions.
$ErrorActionPreference = 'Continue'
try {
    # The build scripts' own flags; the compiler runs from the work directory because the
    # repository path has spaces and Watcom splits unquoted arguments on them.
    & $wcl '-bt=nt' '-q' '-5s' '-ox' '-zp8' '-zq' '-za99' '-i=..\..\src\runtime' `
           '-i=..\..\src\runtime\plat\win32' 'main.c' '..\..\src\runtime\plat\win32\plat_win32.c' `
           '..\..\src\runtime\plat\win32\border.c' '-fe=keys-check.exe' 2>&1 | Out-Null
    $built = $LASTEXITCODE -eq 0 -and (Test-Path 'keys-check.exe')
} finally {
    $ErrorActionPreference = $prevEap
    Pop-Location
}
if (-not $built) { Write-Output 'FAIL keys: the check driver did not build'; exit 1 }

$out = & (Join-Path (Resolve-Path $Work).Path 'keys-check.exe') 2>&1
$code = $LASTEXITCODE
$text = ($out | Out-String).Replace("`r`n", "`n").TrimEnd()
Write-Output $text
if ($code -eq 2) { exit 0 }
if ($code -ne 0 -or $text -match '(?m)^FAIL') { exit 1 }
exit 0
