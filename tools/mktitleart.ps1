# Converts the title art into the C table the front ends draw before the engine boots
# (src\host\title_art.h).
#
#   powershell -ExecutionPolicy Bypass -File tools\mktitleart.ps1
#
# The picture is kept byte-exact: one byte per pixel, which is already the framebuffer's own
# format, plus the palette it was drawn with. That is why the PNG has to be 320x200 and indexed
# (8 bits per pixel) - there is no quantisation step here, and none is wanted for a still.
param(
    [string]$Png = "assets\titlescreen.png",
    [string]$Out = "src\host\title_art.h"
)

Add-Type -AssemblyName System.Drawing

$im = [System.Drawing.Bitmap]::FromFile((Resolve-Path $Png))
$w = $im.Width
$h = $im.Height
if ($w -ne 320 -or $h -ne 200) {
    $im.Dispose()
    throw "$Png is ${w}x${h}; the title art must be 320x200"
}
if ($im.PixelFormat -ne [System.Drawing.Imaging.PixelFormat]::Format8bppIndexed) {
    $fmt = $im.PixelFormat
    $im.Dispose()
    throw "$Png is $fmt; save it as an 8-bit indexed PNG"
}

# The indices exactly as stored, through LockBits so nothing is remapped on the way.
$rect = New-Object System.Drawing.Rectangle 0, 0, $w, $h
$data = $im.LockBits($rect, [System.Drawing.Imaging.ImageLockMode]::ReadOnly,
                     [System.Drawing.Imaging.PixelFormat]::Format8bppIndexed)
$raw = New-Object byte[] ($data.Stride * $h)
[System.Runtime.InteropServices.Marshal]::Copy($data.Scan0, $raw, 0, $raw.Length)
$stride = $data.Stride
$im.UnlockBits($data)

$pal = $im.Palette.Entries
$im.Dispose()

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("/* Generated by tools\mktitleart.ps1 from $Png - do not edit. */")
[void]$sb.AppendLine("#define TITLE_W $w")
[void]$sb.AppendLine("#define TITLE_H $h")
[void]$sb.AppendLine("#define TITLE_PAL_ENTRIES 256")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("/* The palette the picture was drawn with, RGB, unchanged. */")
[void]$sb.AppendLine("static const u8 g_titlePal[TITLE_PAL_ENTRIES * 3] =")
[void]$sb.AppendLine("{")
$line = "    "
for ($i = 0; $i -lt 256; $i++) {
    $c = if ($i -lt $pal.Count) { $pal[$i] } else { [System.Drawing.Color]::Black }
    $line += ("{0},{1},{2}," -f $c.R, $c.G, $c.B)
    if ((($i + 1) % 8) -eq 0) { [void]$sb.AppendLine($line.TrimEnd()); $line = "    " }
}
if ($line.Trim().Length -gt 0) { [void]$sb.AppendLine($line.TrimEnd()) }
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("/* One byte per pixel, row by row - the platform framebuffer's format. */")
[void]$sb.AppendLine("static const u8 g_titleImg[TITLE_H * TITLE_W] =")
[void]$sb.AppendLine("{")
for ($y = 0; $y -lt $h; $y++) {
    $line = "    "
    for ($x = 0; $x -lt $w; $x++) {
        $line += ("{0}," -f $raw[$y * $stride + $x])
        if ((($x + 1) % 32) -eq 0) { [void]$sb.AppendLine($line.TrimEnd()); $line = "    " }
    }
    if ($line.Trim().Length -gt 0) { [void]$sb.AppendLine($line.TrimEnd()) }
}
[void]$sb.AppendLine("};")

$text = $sb.ToString().Replace("`r`n", "`n")
[IO.File]::WriteAllText((Join-Path (Get-Location) $Out), $text, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "wrote $Out ($w x $h, $($pal.Count) palette entries)"
