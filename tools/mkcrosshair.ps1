# Writes src\runtime\amiga\crosshair_art.h: the aiming aid the giant-ant fight shows.
#
#   powershell -ExecutionPolicy Bypass -File tools\mkcrosshair.ps1
#
# The port's own artwork (assets\crosshair.png), not decoded from the game: a 9x9 cross with a
# one-pixel hole in the middle, so its centre is the point it marks. The runtime draws it with the
# pens the on-screen display reserves and sets (OSD_PEN_CRS, OSD_PEN_CRS+1, ...), on top of the
# presented picture - it costs the machine no state at all.
#
# The centre pixel is the mark: a 9x9 picture puts it at (4,4), i.e. every drawn pixel lands at
# (centre + column - 4, centre + row - 4). Any size works as long as it is odd on both axes.
param(
    [string]$In  = "assets\crosshair.png",
    [string]$Out = "src\runtime\amiga\crosshair_art.h",
    [int]$MaxColours = 7               # OSD_PEN_CRS..(OSD_PEN_CRS+6): 248..254, 255 is the OSD text
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

if (-not (Test-Path $In)) { throw "no $In - the crosshair artwork lives in assets\" }
Add-Type -AssemblyName System.Drawing

$img = [System.Drawing.Bitmap]::new((Resolve-Path $In).Path)
$w = $img.Width
$h = $img.Height
if (($w % 2) -ne 1 -or ($h % 2) -ne 1) { $img.Dispose(); throw "$In is $($w)x$($h): the centre pixel must exist" }

# Colours in first-seen order, so the header is stable for a given picture.
$index = @{}                         # "r,g,b" -> pen offset (1-based)
$pal = New-Object System.Collections.Generic.List[int]
$pixels = New-Object int[] ($w * $h)
for ($y = 0; $y -lt $h; $y++) {
    for ($x = 0; $x -lt $w; $x++) {
        $p = $img.GetPixel($x, $y)
        $i = $y * $w + $x
        if ($p.A -eq 0) { $pixels[$i] = 0; continue }
        $key = "$($p.R),$($p.G),$($p.B)"
        if (-not $index.ContainsKey($key)) {
            if ($index.Count -ge $MaxColours) {
                $img.Dispose()
                throw "$In has more than $MaxColours colours - raise OSD_PEN_CRS' room in display.c"
            }
            $index[$key] = $index.Count + 1
            $pal.Add($p.R); $pal.Add($p.G); $pal.Add($p.B)
        }
        $pixels[$i] = $index[$key]
    }
}
$img.Dispose()
$n = $index.Count

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("/* Generated by tools\mkcrosshair.ps1 from $In - the port's aiming aid. Do not edit. */")
[void]$sb.AppendLine("#define CRS_W $w")
[void]$sb.AppendLine("#define CRS_H $h")
[void]$sb.AppendLine("#define CRS_COLOURS $n")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("/* RGB of the non-transparent colours, in index order. */")
[void]$sb.AppendLine("static const u8 g_crosshairPal[CRS_COLOURS * 3] =")
[void]$sb.AppendLine("{")
[void]$sb.AppendLine("    " + ($pal -join ', ') + ",")
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("/* One byte per pixel, row by row: 0 = transparent, n = colour n-1. */")
[void]$sb.AppendLine("static const u8 g_crosshair[CRS_H * CRS_W] =")
[void]$sb.AppendLine("{")
for ($y = 0; $y -lt $h; $y++) {
    $row = @()
    for ($x = 0; $x -lt $w; $x++) { $row += $pixels[$y * $w + $x] }
    [void]$sb.AppendLine("    " + ($row -join ',') + ",")
}
[void]$sb.AppendLine("};")

$text = $sb.ToString().Replace("`r`n", "`n")
[IO.File]::WriteAllText((Join-Path (Get-Location) $Out), $text, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "wrote $Out ($w x $h, $n colour(s))"
