<#
.SYNOPSIS
    Writes a minimal, deterministic WinUAE configuration that boots the three game disks.

.DESCRIPTION
    A fixed reference setup matters for the M2 acceptance test: the same chipset, the same
    memory and the same disks every time, so a capture can be repeated later.

    Launch with:   E:\Meine Programme\WinUAE\winuae64.exe -f tools\icftd.uae

    Screen geometry is deliberately left at WinUAE's defaults (the game sets its own View), so a
    grab usually has borders around the 320x200 area - crop it when comparing:
        tools\diff-frame.ps1 -A out\shot.bmp -B ref\title.png -CropB "x,y,320,200"

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\make-winuae-config.ps1 -Rom "C:\roms\kick13.rom"
#>
param(
    [Parameter(Mandatory = $true)][string]$Rom,
    [string]$Out = "tools\icftd.uae",
    [string]$DiskDir = "disks",
    [string]$WinUAE = "E:\Meine Programme\WinUAE"
)
$ErrorActionPreference = 'Stop'

if (-not (Test-Path -LiteralPath $Rom)) { throw "kickstart ROM not found: $Rom" }
$romFull = (Get-Item -LiteralPath $Rom).FullName

$disks = Get-ChildItem -LiteralPath $DiskDir -Filter *.adf | Sort-Object Name
if ($disks.Count -lt 1) { throw "no .adf files in '$DiskDir'" }
# -LiteralPath matters: the ADF names contain "[!]", which PowerShell would treat as a wildcard.
$diskPaths = @($disks | ForEach-Object { $_.FullName })

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('; Generated by tools\make-winuae-config.ps1 - do not edit by hand.')
$lines.Add('config_description=ICFTD reference (A500, OCS, 1MB chip)')
$lines.Add('use_gui=no')
$lines.Add("kickstart_rom_file=$romFull")
$lines.Add('cpu_type=68000')
$lines.Add('cpu_compatible=true')
$lines.Add('cpu_speed=max')
$lines.Add('cpu_24bit_addressing=true')
$lines.Add('chipset=ocs')
$lines.Add('chipmem_size=2')          # 1 MB; the value is in half-megabyte units
$lines.Add('bogomem_size=0')
$lines.Add('fastmem_size=0')
$lines.Add('z3mem_size=0')
$lines.Add('gfx_framerate=1')
$lines.Add('gfx_fullscreen_amiga=false')
$lines.Add('gfx_correct_aspect=false')
$lines.Add('window_statusbar=false')
$lines.Add('sound_output=none')
$lines.Add('joyport0=mouse')
$lines.Add('joyport1=none')
for ($i = 0; $i -lt 4; $i++) {
    if ($i -lt $diskPaths.Count) {
        $p = $diskPaths[$i]
        $lines.Add("floppy$($i)type=0")
        $lines.Add("floppy$($i)=$p")
    }
    else {
        $lines.Add("floppy$($i)type=-1")
    }
}

$dir = Split-Path -Parent $Out
if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
Set-Content -Path $Out -Value $lines -Encoding ASCII

"wrote $Out"
"  rom:   $romFull"
for ($i = 0; $i -lt $disks.Count; $i++) { "  df$i`:  $($disks[$i].Name)" }
$exe = Join-Path $WinUAE 'winuae64.exe'
if (Test-Path -LiteralPath $exe) {
    ""
    "next:"
    "  & '$exe' -f '$(Get-Item -LiteralPath $Out | ForEach-Object { $_.FullName })'"
    "  powershell -ExecutionPolicy Bypass -File tools\freeze-frame.ps1 -Title WinUAE -Out ref\title.png"
}
